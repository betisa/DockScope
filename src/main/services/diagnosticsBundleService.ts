import os from 'node:os'
import path from 'node:path'
import type {
  DiagnosticsBundleCollector,
  DiagnosticsBundleExportResult,
  DiagnosticsBundleManifest
} from '../../shared/contracts'
import { dockerService } from './dockerService'
import { windowsStorageService } from './windowsStorageService'
import { operationalIntelligence } from '../monitoring/operationalIntelligence'
import { auditService } from './auditService'
import { applicationSettingsService } from './applicationSettingsService'
import { taskCenterService } from './taskCenterService'
import { storageTrendService } from './storageTrendService'
import { run } from './processRunner'
import { writeZip } from './simpleZip'

const MAX_CONTAINERS = 25
const LOG_TAIL_LINES = 300

type BundleFile = { name: string; content: string | Buffer }

function sanitizePathText(value: string) {
  const home = os.homedir()
  const normalizedHome = home.replaceAll('\\', '/')
  return value
    .replaceAll(home, '%USERPROFILE%')
    .replaceAll(normalizedHome, '%USERPROFILE%')
}

function redactString(value: string) {
  return sanitizePathText(value)
    .replace(/((?:password|passwd|pwd|secret|token|api[_-]?key|client[_-]?secret|access[_-]?key|private[_-]?key)\s*[=:]\s*)([^\s"'`]+)/gi, '$1***')
    .replace(/(authorization\s*:\s*bearer\s+)([^\s"'`]+)/gi, '$1***')
    .replace(/((?:connectionstring|connection_string)\s*[=:]\s*)([^\r\n]+)/gi, '$1***')
    .replace(/((?:postgres|postgresql|mysql|mariadb|mongodb(?:\+srv)?|redis):\/\/[^:\s/@]+:)([^@\s/]+)(@)/gi, '$1***$3')
    .replace(/(https?:\/\/)([^:\s/@]+):([^@\s/]+)@/gi, '$1$2:***@')
}

function sensitiveKey(key: string) {
  return /password|passwd|pwd|secret|token|api.?key|client.?secret|access.?key|private.?key|authorization|credential|connection.?string/i.test(key)
}

function redactValue(value: unknown, key = ''): unknown {
  if (sensitiveKey(key)) return '***'
  if (typeof value === 'string') {
    if (/^[A-Za-z_][A-Za-z0-9_]*=/.test(value)) {
      const index = value.indexOf('=')
      const envKey = value.slice(0, index)
      const envValue = value.slice(index + 1)
      return `${envKey}=${sensitiveKey(envKey) ? '***' : redactString(envValue)}`
    }
    return redactString(value)
  }
  if (Array.isArray(value)) return value.map(item => redactValue(item))
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value as Record<string, unknown>)
        .map(([childKey, childValue]) => [childKey, redactValue(childValue, childKey)])
    )
  }
  return value
}

function json(value: unknown) {
  return JSON.stringify(redactValue(value), null, 2)
}

function text(value: string) {
  return redactString(value)
}

function safeFileSegment(value: string) {
  return value.replace(/[^a-zA-Z0-9_.-]+/g, '_').slice(0, 90) || 'resource'
}

function commandText(result: { stdout: string; stderr: string; ok: boolean }) {
  const value = result.stdout || result.stderr
  return text(value || (result.ok ? 'Command completed with no output.' : 'Command failed with no output.'))
}

function supportReadme(generatedAt: string) {
  return `DockScope — Diagnostics Bundle

Generated: ${generatedAt}

PURPOSE
This bundle is intended for troubleshooting DockScope and local Docker Desktop / Docker Engine issues.

PRIVACY & REDACTION
- Common secret-like keys and values are masked before files are added to the ZIP.
- Bearer tokens, common connection-string patterns and credential-bearing URLs are masked.
- The current user's home-directory prefix is replaced with %USERPROFILE%.
- Container environment values whose keys look secret-like are masked.
- Redaction is best-effort. Review the bundle before sharing it outside your trusted support channel.

CONTENTS
- manifest.json: collector status, limits and warnings.
- system/: application, OS and Docker command information.
- docker/: resource inventories and dependency information.
- containers/: diagnostics metadata and recent log tails for up to ${MAX_CONTAINERS} containers.
- storage/: Docker Desktop VHDX information when available.
- monitoring/: current health and notification history.
- operations/: Task Center and Audit / Recovery metadata.

LIMITATIONS
- This is a metadata/diagnostics bundle, not a backup.
- Volume contents are never copied into this bundle.
- Full container filesystems are never copied.
- Only the latest ${LOG_TAIL_LINES} container log lines are requested.
- At most ${MAX_CONTAINERS} containers receive per-container diagnostics/log files.
- Collector failure does not abort the entire export; see manifest.json.

Generated by DockScope Desktop ${app.getVersion()}.
`
}

class DiagnosticsBundleService {
  async exportTo(target: string): Promise<DiagnosticsBundleExportResult> {
    const generatedAt = new Date().toISOString()
    const files: BundleFile[] = []
    const collectors: DiagnosticsBundleCollector[] = []
    const warnings: string[] = []

    const add = (name: string, content: string | Buffer) => {
      files.push({ name, content })
      return Buffer.isBuffer(content) ? content.length : Buffer.byteLength(content, 'utf8')
    }

    const collect = async (
      collectorName: string,
      file: string,
      action: () => Promise<string | Buffer> | string | Buffer
    ) => {
      try {
        const content = await action()
        const bytes = add(file, content)
        collectors.push({ name: collectorName, file, status: 'success', message: '', bytes })
      } catch (error) {
        collectors.push({
          name: collectorName,
          file,
          status: 'failed',
          message: redactString(error instanceof Error ? error.message : String(error)),
          bytes: 0
        })
      }
    }

    const skip = (collectorName: string, file: string, message: string) => {
      collectors.push({ name: collectorName, file, status: 'skipped', message, bytes: 0 })
    }

    add('README.txt', supportReadme(generatedAt))

    await collect('Application and OS', 'system/app.json', () => json({
      application: {
        name: app.getName(),
        version: app.getVersion(),
        packaged: app.isPackaged
      },
      runtime: {
        electron: process.versions.electron,
        node: process.versions.node,
        chrome: process.versions.chrome,
        v8: process.versions.v8
      },
      operatingSystem: {
        platform: process.platform,
        arch: process.arch,
        release: os.release(),
        version: os.version(),
        type: os.type(),
        totalMemoryBytes: os.totalmem(),
        freeMemoryBytes: os.freemem(),
        cpuCount: os.cpus().length
      }
    }))

    await collect('Application settings', 'system/settings.json', async () => {
      await applicationSettingsService.initialize()
      return json(applicationSettingsService.get())
    })

    await collect('Docker version', 'system/docker-version.txt', async () =>
      commandText(await run('docker', ['version']))
    )
    await collect('Docker info', 'system/docker-info.txt', async () =>
      commandText(await run('docker', ['info']))
    )
    await collect('Docker context', 'system/docker-context.txt', async () =>
      commandText(await run('docker', ['context', 'show']))
    )

    await collect('Engine status', 'docker/engine-status.json', async () => json(await dockerService.engineStatus()))
    await collect('Disk usage', 'docker/disk-usage.json', async () => json(await dockerService.diskUsage()))
    await collect('Container inventory', 'docker/containers.json', async () => json(await dockerService.containers()))
    await collect('Compose projects', 'docker/compose-projects.json', async () => json(await dockerService.composeProjects()))
    await collect('Images', 'docker/images.json', async () => json(await dockerService.images()))
    await collect('Networks', 'docker/networks.json', async () => json(await dockerService.networks()))
    await collect('Port Explorer', 'docker/ports.json', async () => json(await dockerService.portExplorer()))
    await collect('Resource Dependency Graph', 'docker/resource-graph.json', async () => json(await dockerService.resourceDependencyGraph()))
    await collect('Volume Intelligence', 'docker/volumes.json', async () => json(await dockerService.volumeIntelligence()))
    await collect('Buildx builders', 'docker/builders.json', async () => json(await dockerService.builders()))
    await collect('Buildx history', 'docker/build-history.json', async () => json(await dockerService.buildHistory()))
    await collect('Build cache', 'docker/build-cache.json', async () => json(await dockerService.buildCacheDiskUsage()))

    const containers = await dockerService.containers().catch(() => [])
    if (containers.length > MAX_CONTAINERS) {
      warnings.push(`Per-container diagnostics were limited to ${MAX_CONTAINERS} of ${containers.length} containers.`)
    }

    for (const container of containers.slice(0, MAX_CONTAINERS)) {
      const segment = `${safeFileSegment(container.name)}-${safeFileSegment(container.id.slice(0, 12))}`
      await collect(
        `Container diagnostics: ${container.name}`,
        `containers/${segment}/diagnostics.json`,
        async () => json(await dockerService.diagnostics(container.id))
      )
      await collect(
        `Container logs: ${container.name}`,
        `containers/${segment}/logs.txt`,
        async () => commandText(await dockerService.logs(container.id, LOG_TAIL_LINES))
      )
    }

    if (!containers.length) {
      skip('Per-container diagnostics', 'containers/', 'No containers were available.')
    }

    await collect('VHDX information', 'storage/vhdx.json', async () => json(await windowsStorageService.findVhdx()))
    await collect('Storage Trends (30 days)', 'storage/storage-trends-30d.json', async () => json(await storageTrendService.trends('30d')))
    await collect('Operational health', 'monitoring/health.json', () => json(operationalIntelligence.getHealth()))
    await collect('Notifications', 'monitoring/notifications.json', () => json(operationalIntelligence.listNotifications()))
    await collect('Task Center', 'operations/tasks.json', async () => json(await taskCenterService.list()))
    await collect('Task Center summary', 'operations/task-summary.json', async () => json(await taskCenterService.summary()))
    await collect('Audit summary', 'operations/audit-summary.json', () => json(auditService.summary()))
    await collect('Audit history', 'operations/audit-history.json', () => json(auditService.list()))
    await collect('Recovery snapshots', 'operations/recovery-snapshots.json', () => json(auditService.snapshots()))

    const failed = collectors.filter(item => item.status === 'failed').length
    if (failed) warnings.push(`${failed} collector(s) failed. Review manifest.json before sharing the bundle.`)
    warnings.push('Redaction is best-effort. Review exported files before sharing outside a trusted support channel.')

    const manifest: DiagnosticsBundleManifest = {
      schemaVersion: 1,
      generatedAt,
      application: {
        name: app.getName(),
        version: app.getVersion(),
        platform: process.platform,
        arch: process.arch
      },
      redaction: {
        enabled: true,
        strategy: 'Recursive key masking + secret-pattern masking + credential URL masking + user-home path normalization'
      },
      limits: {
        maxContainers: MAX_CONTAINERS,
        containerLogTailLines: LOG_TAIL_LINES
      },
      collectors,
      warnings
    }

    add('manifest.json', json(manifest))
    const result = await writeZip(target, files)

    return {
      ok: true,
      path: target,
      message: failed
        ? `Diagnostics bundle created with ${failed} collector warning(s). Review manifest.json before sharing.`
        : 'Diagnostics bundle created. Review the bundle before sharing it.',
      generatedAt,
      fileCount: result.fileCount,
      sizeBytes: result.sizeBytes,
      collectorFailures: failed
    }
  }
}

export const diagnosticsBundleService = new DiagnosticsBundleService()
